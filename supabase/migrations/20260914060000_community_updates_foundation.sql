-- Community Updates / Notices foundation baseline.
-- This baseline represents foundation objects created before remote migration tracking was reconciled.
-- It is ordered before the reconciliation marker so fresh environments can build the foundation before later deltas.
-- Generic update model: notice, announcement, event.
-- Membership targeting uses school_batches (shared context), never user-specific memberships.

create table public.community_updates (
  id bigint generated by default as identity primary key,
  update_type text not null check (update_type in ('notice','announcement','event')),
  visibility_scope text not null check (visibility_scope in ('public','membership_targeted')),
  title text not null check (btrim(title) <> ''),
  content text,
  created_by uuid not null references auth.users(id) on delete restrict,
  published_at timestamptz not null default now(),
  expires_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint community_updates_expiry_after_publish check (expires_at is null or expires_at > published_at)
);

create table public.community_update_memberships (
  update_id bigint not null references public.community_updates(id) on delete cascade,
  school_batch_id bigint not null references public.school_batches(id) on delete restrict,
  created_at timestamptz not null default now(),
  primary key (update_id, school_batch_id)
);

create table public.community_update_event_details (
  update_id bigint primary key references public.community_updates(id) on delete cascade,
  starts_at timestamptz not null,
  ends_at timestamptz,
  location_name text,
  location_url text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint community_update_event_details_end_after_start check (ends_at is null or ends_at >= starts_at)
);

create index community_updates_active_public_idx on public.community_updates (published_at desc)
  where visibility_scope = 'public';
create index community_updates_expires_at_idx on public.community_updates (expires_at);
create index community_updates_type_published_idx on public.community_updates (update_type, published_at desc);
create index community_update_memberships_school_batch_idx
  on public.community_update_memberships (school_batch_id, update_id);

create or replace function public.community_updates_set_updated_at()
returns trigger language plpgsql set search_path to 'public' as $$
begin new.updated_at := now(); return new; end;
$$;

create trigger community_updates_set_updated_at before update on public.community_updates
for each row execute function public.community_updates_set_updated_at();
create trigger community_update_event_details_set_updated_at before update on public.community_update_event_details
for each row execute function public.community_updates_set_updated_at();

create or replace function public.community_updates_event_details_require_event()
returns trigger language plpgsql security definer set search_path to 'public' as $$
begin
  if not exists (select 1 from public.community_updates where id=new.update_id and update_type='event') then
    raise exception 'Event details are only valid for event updates';
  end if;
  return new;
end;
$$;
create trigger community_update_event_details_require_event
before insert or update on public.community_update_event_details
for each row execute function public.community_updates_event_details_require_event();

