create or replace function public.community_updates_is_active_school_batch_member(
  p_school_batch_id bigint, p_user_id uuid default auth.uid()
) returns boolean language sql stable security definer set search_path to 'public' as $$
  select exists (
    select 1 from public.memberships m
    where m.batch_id=p_school_batch_id and m.user_id=p_user_id and m.status='active'
  );
$$;

create or replace function public.community_updates_is_active_school_batch_admin(
  p_school_batch_id bigint, p_user_id uuid default auth.uid()
) returns boolean language sql stable security definer set search_path to 'public' as $$
  select exists (
    select 1 from public.memberships m
    where m.batch_id=p_school_batch_id and m.user_id=p_user_id
      and m.status='active' and m.membership_type='admin'
  );
$$;

create or replace function public.community_updates_can_publish_public(
  p_user_id uuid default auth.uid()
) returns boolean language plpgsql stable security definer set search_path to 'public' as $$
declare v_owner text; v_admin text; v_member text;
begin
  if p_user_id is null then return false; end if;
  select config_value,config_value_2,config_value_3 into v_owner,v_admin,v_member
  from public.site_config
  where config_key='community_updates_public_authority'
    and scope_type='global' and scope_id is null and is_active
  order by config_seq limit 1;

  if public.is_platform_owner() then return coalesce(v_owner,'deny')='allow'; end if;

  if exists (
    select 1 from public.memberships m join public.site_config c
      on c.config_key='community_updates_public_authority'
     and c.scope_type='school_batch' and c.scope_id=m.batch_id and c.is_active
    where m.user_id=p_user_id and m.status='active'
      and ((m.membership_type='admin' and c.config_value_2='allow')
        or (m.membership_type='member' and c.config_value_3='allow'))
  ) then return true; end if;

  return exists (
    select 1 from public.memberships m
    where m.user_id=p_user_id and m.status='active'
      and ((m.membership_type='admin' and coalesce(v_admin,'deny')='allow')
        or (m.membership_type='member' and coalesce(v_member,'deny')='allow'))
  );
end;
$$;

create or replace function public.community_updates_can_manage_targets(
  p_school_batch_ids bigint[], p_user_id uuid default auth.uid()
) returns boolean language plpgsql stable security definer set search_path to 'public' as $$
begin
  if p_user_id is null or p_school_batch_ids is null or cardinality(p_school_batch_ids)=0 then return false; end if;
  if public.is_platform_owner() then return true; end if;
  return not exists (
    select 1 from (select distinct x as school_batch_id from unnest(p_school_batch_ids) x where x is not null) t
    where not public.community_updates_is_active_school_batch_admin(t.school_batch_id,p_user_id)
  );
end;
$$;

create or replace function public.community_updates_can_read(
  p_update_id bigint, p_user_id uuid default auth.uid()
) returns boolean language plpgsql stable security definer set search_path to 'public' as $$
declare v public.community_updates;
begin
  select * into v from public.community_updates where id=p_update_id;
  if not found then return false; end if;
  if p_user_id is not null and (
    public.is_platform_owner() or v.created_by=p_user_id or
    (v.visibility_scope='membership_targeted' and exists (
      select 1 from public.community_update_memberships t
      where t.update_id=v.id and public.community_updates_is_active_school_batch_admin(t.school_batch_id,p_user_id)
    ))
  ) then return true; end if;
  if v.expires_at is not null and v.expires_at<=now() then return false; end if;
  if v.visibility_scope='public' then return true; end if;
  return p_user_id is not null and exists (
    select 1 from public.community_update_memberships t
    where t.update_id=v.id and public.community_updates_is_active_school_batch_member(t.school_batch_id,p_user_id)
  );
end;
$$;

create or replace function public.community_updates_can_manage(
  p_update_id bigint, p_user_id uuid default auth.uid()
) returns boolean language plpgsql stable security definer set search_path to 'public' as $$
declare v_visibility text; v_targets bigint[];
begin
  if p_user_id is null then return false; end if;
  select visibility_scope into v_visibility from public.community_updates where id=p_update_id;
  if not found then return false; end if;
  if v_visibility='public' then return public.community_updates_can_publish_public(p_user_id); end if;
  select array_agg(school_batch_id order by school_batch_id) into v_targets
  from public.community_update_memberships where update_id=p_update_id;
  return public.community_updates_can_manage_targets(v_targets,p_user_id);
end;
$$;

create or replace function public.community_updates_save(
  p_update_id bigint default null,
  p_update_type text default null,
  p_visibility_scope text default null,
  p_title text default null,
  p_content text default null,
  p_expires_at timestamptz default null,
  p_school_batch_ids bigint[] default null,
  p_event_starts_at timestamptz default null,
  p_event_ends_at timestamptz default null,
  p_event_location_name text default null,
  p_event_location_url text default null
) returns public.community_updates language plpgsql security definer set search_path to 'public' as $$
declare v_user uuid:=auth.uid(); v public.community_updates; v_targets bigint[]; v_count int;
begin
  if v_user is null then raise exception 'Authentication is required'; end if;
  if p_update_type not in ('notice','announcement','event') then raise exception 'Unsupported update type'; end if;
  if p_visibility_scope not in ('public','membership_targeted') then raise exception 'Unsupported visibility scope'; end if;
  if p_title is null or btrim(p_title)='' then raise exception 'Community Update title is required'; end if;
  if p_expires_at is not null and p_expires_at<=now() then raise exception 'expires_at must be in the future'; end if;

  select array_agg(distinct x order by x),count(distinct x) into v_targets,v_count
  from unnest(coalesce(p_school_batch_ids,'{}'::bigint[])) x where x is not null;

  if p_visibility_scope='public' then
    if coalesce(v_count,0)<>0 then raise exception 'Public updates cannot have school-batch targets'; end if;
    if not public.community_updates_can_publish_public(v_user) then raise exception 'Not allowed to publish public Community Updates'; end if;
  else
    if coalesce(v_count,0)=0 then raise exception 'At least one school-batch target is required'; end if;
    if exists (select 1 from unnest(v_targets) x where not exists (
      select 1 from public.school_batches sb where sb.id=x and sb.is_active
    )) then raise exception 'Invalid or inactive school-batch target'; end if;
    if not public.community_updates_can_manage_targets(v_targets,v_user) then
      raise exception 'You must be an active admin of every targeted school batch';
    end if;
  end if;

  if p_update_type='event' then
    if p_event_starts_at is null then raise exception 'Event start time is required'; end if;
    if p_event_ends_at is not null and p_event_ends_at<p_event_starts_at then raise exception 'Event end time cannot be before event start time'; end if;
  elsif p_event_starts_at is not null or p_event_ends_at is not null
     or nullif(btrim(coalesce(p_event_location_name,'')),'') is not null
     or nullif(btrim(coalesce(p_event_location_url,'')),'') is not null then
    raise exception 'Event details are only valid for event updates';
  end if;

  if p_update_id is null then
    insert into public.community_updates(update_type,visibility_scope,title,content,created_by,published_at,expires_at)
    values(p_update_type,p_visibility_scope,btrim(p_title),nullif(btrim(coalesce(p_content,'')),''),v_user,now(),p_expires_at)
    returning * into v;
  else
    if not public.community_updates_can_manage(p_update_id,v_user) then raise exception 'Not allowed to manage this Community Update'; end if;
    update public.community_updates set update_type=p_update_type,visibility_scope=p_visibility_scope,
      title=btrim(p_title),content=nullif(btrim(coalesce(p_content,'')),''),expires_at=p_expires_at
    where id=p_update_id returning * into v;
  end if;

  delete from public.community_update_memberships where update_id=v.id;
  if p_visibility_scope='membership_targeted' then
    insert into public.community_update_memberships(update_id,school_batch_id)
    select v.id,x from unnest(v_targets) x;
  end if;

  delete from public.community_update_event_details where update_id=v.id;
  if p_update_type='event' then
    insert into public.community_update_event_details(update_id,starts_at,ends_at,location_name,location_url)
    values(v.id,p_event_starts_at,p_event_ends_at,
      nullif(btrim(coalesce(p_event_location_name,'')),''),nullif(btrim(coalesce(p_event_location_url,'')),'')); 
  end if;
  return v;
end;
$$;

create or replace function public.community_updates_delete(p_update_id bigint)
returns void language plpgsql security definer set search_path to 'public' as $$
begin
  if auth.uid() is null then raise exception 'Authentication is required'; end if;
  if not public.community_updates_can_manage(p_update_id,auth.uid()) then raise exception 'Not allowed to delete this Community Update'; end if;
  delete from public.community_updates where id=p_update_id;
  if not found then raise exception 'Community Update not found'; end if;
end;
$$;

